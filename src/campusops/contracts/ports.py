"""Stable feature-branch interfaces. Collections serialize to JSON arrays."""

from typing import Protocol, runtime_checkable

from campusops.contracts.models import (
    AgentConfig, AgentConfigPatch, ApprovalDecision, ApplyResult, BookingRules, Equipment, ExecutionMode,
    Incident, IncidentCreate, ModelBudgetSnapshot, ModelRequest, ModelResponse, ModelUsage, PlanResult, BookingRuleCatalog,
    Proposal, ProposalItem, Reservation, ResourceSnapshot, RunStep, RunStepCreate,
    ValidationResult, WorkflowRun,
    EquipmentRecoveryCreate, EquipmentRecoveryResult,
    ReservationCreate, ReservationCancelCreate, ReservationMutationResult, ReservationChangeCreate,
    ReservationChangeContext, ReservationChangePolicy, ReservationChangePlanResult,
    ReservationChangeRun, ReservationChangeDecision,
    EquipmentCreate, EquipmentUpdate, EquipmentArchiveCreate, EquipmentRestoreCreate,
    EquipmentCatalogEntry, EquipmentCatalogMutationResult,
)


@runtime_checkable
class ModelClientPort(Protocol):
    def complete(self, request: ModelRequest) -> ModelResponse: ...


@runtime_checkable
class ModelBudgetPort(Protocol):
    def get_model_budget(self, run_id: str) -> ModelBudgetSnapshot: ...


@runtime_checkable
class BookingRulesPort(Protocol):
    """Optional current-rule query for UI; original ApplicationPort is unchanged."""

    def get_booking_rules(self) -> BookingRuleCatalog: ...


@runtime_checkable
class IdempotentWorkflowPort(Protocol):
    """Optional persistent start deduplication; the legacy start signature stays."""

    def start_workflow_once(self, incident_id: str, idempotency_key: str) -> PlanResult: ...


@runtime_checkable
class EquipmentMaintenancePort(Protocol):
    """Optional explicit repair; not available to model read-only tools."""

    def recover_equipment(self, request: EquipmentRecoveryCreate) -> EquipmentRecoveryResult: ...


@runtime_checkable
class ReadonlyPort(Protocol):
    def get_incident(self, incident_id: str) -> Incident: ...
    def get_impacted_reservations(self, incident_id: str) -> tuple[Reservation, ...]: ...
    def list_equipment_candidates(self, reservation_id: str) -> tuple[Equipment, ...]: ...
    def get_booking_rules(self) -> BookingRules: ...
    def get_snapshot(self) -> ResourceSnapshot: ...
    def list_agent_configs(self) -> tuple[AgentConfig, ...]: ...
    def get_model_usage(self) -> ModelUsage: ...
    def validate_candidate_plan(self, changes: tuple[ProposalItem, ...]) -> ValidationResult: ...
    def append_run_step(self, step: RunStepCreate) -> RunStep: ...


@runtime_checkable
class OrchestrationPort(Protocol):
    def run_incident(
        self, incident_id: str, run_id: str, readonly_port: ReadonlyPort,
        model_client: ModelClientPort | None,
    ) -> PlanResult: ...


@runtime_checkable
class ApplicationPort(Protocol):
    def list_equipment(self) -> tuple[Equipment, ...]: ...
    def list_reservations(self) -> tuple[Reservation, ...]: ...
    def list_incidents(self) -> tuple[Incident, ...]: ...
    def list_runs(self) -> tuple[WorkflowRun, ...]: ...
    def list_agent_configs(self) -> tuple[AgentConfig, ...]: ...
    def list_run_steps(self, run_id: str) -> tuple[RunStep, ...]: ...
    def register_equipment_failure(self, incident: IncidentCreate) -> Incident: ...
    def start_workflow(self, incident_id: str) -> PlanResult: ...
    def get_run(self, run_id: str) -> WorkflowRun: ...
    def get_proposal(self, proposal_id: str) -> Proposal: ...
    def get_approval_decision(self, proposal_id: str) -> ApprovalDecision | None: ...
    def get_model_budget(self, run_id: str) -> ModelBudgetSnapshot: ...
    def approve_proposal(self, proposal_id: str, actor_alias: str, idempotency_key: str) -> ApplyResult: ...
    def reject_proposal(self, proposal_id: str, actor_alias: str, reason: str) -> ApplyResult: ...
    def update_agent_config(self, agent_id: str, patch: AgentConfigPatch) -> AgentConfig: ...
    def reset_demo_data(self, confirmation: str) -> None: ...


@runtime_checkable
class ReservationManagementPort(Protocol):
    def create_reservation(self, request: ReservationCreate) -> ReservationMutationResult: ...
    def cancel_reservation(self, request: ReservationCancelCreate) -> ReservationMutationResult: ...
    def find_reservation_command(self, idempotency_key: str) -> ReservationMutationResult | None: ...
    def plan_reservation_change(self, request: ReservationChangeCreate) -> ReservationChangeRun: ...
    def get_reservation_change(self, change_id: str) -> ReservationChangeRun: ...
    def list_reservation_changes(self, reservation_id: str | None = None) -> tuple[ReservationChangeRun, ...]: ...
    def approve_reservation_change(self, change_id: str, actor_alias: str, idempotency_key: str) -> ReservationChangeDecision: ...
    def reject_reservation_change(self, change_id: str, actor_alias: str, reason: str) -> ReservationChangeDecision: ...
    def get_reservation_change_budget(self, change_id: str) -> ModelBudgetSnapshot: ...


@runtime_checkable
class ReservationChangeReadonlyPort(Protocol):
    """Run-bound change context. get_incident is a compatibility tool name, never a fault record."""
    def get_incident(self, incident_id: str) -> ReservationChangeContext: ...
    def get_impacted_reservations(self, incident_id: str) -> tuple[Reservation, ...]: ...
    def list_equipment_candidates(self, reservation_id: str) -> tuple[Equipment, ...]: ...
    def get_booking_rules(self) -> ReservationChangePolicy: ...
    def get_snapshot(self) -> ResourceSnapshot: ...
    def list_agent_configs(self) -> tuple[AgentConfig, ...]: ...
    def get_model_usage(self) -> ModelUsage: ...
    def validate_candidate_plan(self, changes: tuple[ProposalItem, ...]) -> ValidationResult: ...
    def append_run_step(self, step: RunStepCreate) -> RunStep: ...


@runtime_checkable
class ReservationChangeOrchestrationPort(Protocol):
    def run_reservation_change(self, change_id: str, readonly_port: ReservationChangeReadonlyPort,
                               model_client: ModelClientPort | None) -> ReservationChangePlanResult: ...


@runtime_checkable
class EquipmentCatalogPort(Protocol):
    def list_equipment_catalog(self, include_archived: bool = False) -> tuple[EquipmentCatalogEntry, ...]: ...
    def create_equipment(self, request: EquipmentCreate) -> EquipmentCatalogMutationResult: ...
    def update_equipment(self, request: EquipmentUpdate) -> EquipmentCatalogMutationResult: ...
    def archive_equipment(self, request: EquipmentArchiveCreate) -> EquipmentCatalogMutationResult: ...
    def restore_equipment(self, request: EquipmentRestoreCreate) -> EquipmentCatalogMutationResult: ...
    def find_equipment_command(self, idempotency_key: str) -> EquipmentCatalogMutationResult | None: ...


PUBLIC_PORTS = (ModelClientPort, ReadonlyPort, OrchestrationPort, ApplicationPort, ModelBudgetPort,
                BookingRulesPort, IdempotentWorkflowPort, EquipmentMaintenancePort,
                ReservationManagementPort, ReservationChangeReadonlyPort, ReservationChangeOrchestrationPort, EquipmentCatalogPort)
